import { ATLAS_GENERATOR } from "./atlasFormat";
import type { AtlasMeta } from "./atlasFormat";
import { exportIdentifiers } from "./names";
import runtimeSource from "./sprite-runtime.ts?raw";

// The writer of `<name>.sprites.ts` (SPEC §9.5): the atlas data, the functions a game calls,
// and the sprite runtime, copied from sprite-runtime.ts as text.

/** The line of sprite-runtime.ts after which the copied text starts. */
export const RUNTIME_BEGIN = "// sprite-runtime:begin";

/** The line of sprite-runtime.ts before which the copied text ends. */
export const RUNTIME_END = "// sprite-runtime:end";

/**
 * The part of sprite-runtime.ts a generated module carries: the lines between the two
 * marker lines, each as it is in the file and ended by a line feed. What lies outside the
 * markers (the file's head comment and its `export` lines) is left out.
 */
export function runtimeText(source: string = runtimeSource): string {
    const lines = source.replace(/\r\n?/g, "\n").split("\n");
    const begin = lines.indexOf(RUNTIME_BEGIN);
    const end = lines.indexOf(RUNTIME_END);
    if (begin === -1 || end <= begin) {
        throw new Error("sprite-runtime.ts does not have its two marker lines in order.");
    }
    return lines
        .slice(begin + 1, end)
        .map((line) => `${line}\n`)
        .join("");
}

/**
 * The text of `<name>.sprites.ts` for an atlas. `name` is `<name>` (`exportName`): it names
 * the image file beside the module, is the ID of the image asset and of the texture, and
 * gives the identifiers their two forms (`exportIdentifiers`).
 *
 * The module imports `@ngne/core` and nothing else, and exports:
 * - `<name>Image`: the image asset, to be listed in a scene's `assets`;
 * - `<name>Atlas`: the content of `<name>.atlas.json`, `as const`;
 * - the types `<Name>FrameId` and `<Name>AnimationId`: the IDs of the atlas;
 * - `draw<Name>` and `draw<Name>TopLeft`: a frame at its pivot, or at the top-left corner
 *   of its source frame;
 * - `<name>AnimationFrame` and `<name>AnimationDone`.
 *
 * A name reaches the text only as a slug or an identifier made of ASCII letters, digits
 * and "-", so nothing in it needs escaping. The text is ASCII and ends lines with "\n".
 */
export function spritesModuleText(meta: AtlasMeta, name: string): string {
    const { camel, pascal } = exportIdentifiers(name);
    const atlas = `${camel}Atlas`;
    const frameIds = `${pascal}FrameId`;
    const animationIds = `${pascal}AnimationId`;
    const head = `// Generated by ${ATLAS_GENERATOR}. Do not edit: export the sprite again instead.
//
// The sprite sheet ${name}.png for NGNE (@ngne/core): its image asset, the content of
// ${name}.atlas.json, and the functions that draw its frames and resolve its animations.

import { imageAsset } from "@ngne/core";
import type { Frame, ImageAsset } from "@ngne/core";

/**
 * The atlas image, ${name}.png beside this module. List it in the \`assets\` of every scene
 * that draws these frames: its ID is the texture they are drawn from.
 */
export const ${camel}Image: ImageAsset = imageAsset(
    "${name}",
    new URL("./${name}.png", import.meta.url).href,
);

/** The content of ${name}.atlas.json (format \`ngne-sprite-atlas\`, version ${meta.version}). */
export const ${atlas} = ${JSON.stringify(meta, null, 4)} as const;

/** The ID of a frame of the sheet. */
export type ${frameIds} = keyof typeof ${atlas}.frames;

/** The ID of an animation of the sheet. */
export type ${animationIds} = keyof typeof ${atlas}.animations;

/**
 * Draws a frame with its pivot on (\`x\`, \`y\`). The options rotate (radians), scale and
 * mirror it about that point, and pass \`layer\`, \`depth\`, \`alpha\`, \`color\` and \`screen\` on
 * to the engine. Without rotation and with a whole-number scale, a frame at whole-number
 * coordinates covers whole pixels.
 */
export function draw${pascal}(
    frame: Frame,
    id: ${frameIds},
    x: number,
    y: number,
    options?: DrawOptions,
): void {
    spriteAt<${frameIds}>(frame, ${atlas}, "${name}", id, x, y, options);
}

/**
 * Draws a frame with the top-left corner of its source frame on (\`x\`, \`y\`), whatever its
 * pivot and however it was trimmed. The options work about that corner.
 */
export function draw${pascal}TopLeft(
    frame: Frame,
    id: ${frameIds},
    x: number,
    y: number,
    options?: DrawOptions,
): void {
    spriteAtTopLeft<${frameIds}>(frame, ${atlas}, "${name}", id, x, y, options);
}

/**
 * The frame an animation shows \`ageMs\` milliseconds after its start. An entry shows from its
 * start up to, not including, its end. A "loop" animation starts over after its last entry;
 * a "once" animation stays on it.
 */
export function ${camel}AnimationFrame(animation: ${animationIds}, ageMs: number): ${frameIds} {
    return animationFrame<${frameIds}, ${animationIds}>(${atlas}, animation, ageMs);
}

/** True when a "once" animation has reached its end. Never true for a "loop" animation. */
export function ${camel}AnimationDone(animation: ${animationIds}, ageMs: number): boolean {
    return animationDone<${frameIds}, ${animationIds}>(${atlas}, animation, ageMs);
}

// What follows is the same in every module that ngne-sprite-editor exports.

`;
    return head + runtimeText();
}

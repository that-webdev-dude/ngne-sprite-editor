import type { SpriteDoc } from "../model";
import { ATLAS_GENERATOR } from "./atlasFormat";
import type { AtlasMeta } from "./atlasFormat";
import type { ExportPlan } from "./exportPlan";
import { frameId } from "./names";

// The text of the data files of a bundle (SPEC §9.1): `<name>.atlas.json`,
// `<name>.preview.config.mjs` and `<name>.aseprite.json`. Each is a function of its
// arguments alone: no clock, no random value, no locale. Lines end with "\n" and the text
// ends with one. `<name>.sprites.ts` has its writer in spritesModule.ts.

/**
 * The text of `<name>.atlas.json` (docs/FORMAT.md §2): the members in the order of
 * `AtlasMeta`, frames and animations in the order of the atlas, indented by four spaces.
 */
export function atlasJsonText(meta: AtlasMeta): string {
    return `${JSON.stringify(meta, null, 4)}\n`;
}

/**
 * The text of `<name>.preview.config.mjs`: the adapter NGNE's `ngne-preview` loads (SPEC
 * §9.5), with the frames and animations of the atlas as lists.
 *
 * - `src` is a `file:` URL object made from the module's own location, so the folder can be
 *   moved; the preview refuses a relative string.
 * - A frame is shown by its whole atlas rectangle at its own size: `width` and `height` are
 *   the even `w` and `h`, which keeps it on whole pixels of the preview's stage. The adapter
 *   has no place for an offset, so the preview centres a trimmed frame on its rectangle.
 * - An animation's entries are those of the atlas; the adapter has no repeat count.
 */
export function previewConfigText(meta: AtlasMeta, name: string): string {
    const image = JSON.stringify(name);
    const frames = Object.entries(meta.frames).map(
        ([id, { x, y, w, h }]) =>
            `        { id: ${JSON.stringify(id)}, image: ${image}, x: ${x}, y: ${y}, ` +
            `width: ${w}, height: ${h}, destinationWidth: ${w}, destinationHeight: ${h} },\n`,
    );
    const animations = Object.entries(meta.animations).map(([id, { playback, entries }]) => {
        const lines = entries.map(
            ({ frame, ms }) => `                { frame: ${JSON.stringify(frame)}, ms: ${ms} },\n`,
        );
        return (
            `        {\n` +
            `            id: ${JSON.stringify(id)},\n` +
            `            playback: "${playback}",\n` +
            `            entries: [\n${lines.join("")}            ],\n` +
            `        },\n`
        );
    });
    const list = (items: string[]) => (items.length > 0 ? `[\n${items.join("")}    ]` : "[]");
    return `// Generated by ${ATLAS_GENERATOR}. Do not edit: export the sprite again instead.
//
// The sprite sheet ${name}.png for NGNE's preview: npx ngne-preview ./${name}.preview.config.mjs

export default {
    images: [{ id: ${image}, src: new URL("./${name}.png", import.meta.url) }],
    frames: ${list(frames)},
    animations: ${list(animations)},
    display: { density: 1, scale: 1, pixelSnap: true },
};
`;
}

/** A colour 0xRRGGBBAA as Aseprite writes it: `#rrggbbaa`. */
function hexColor(color: number): string {
    return `#${(color >>> 0).toString(16).padStart(8, "0")}`;
}

/**
 * The text of `<name>.aseprite.json`: the atlas as Aseprite's sprite-sheet data (its
 * "Array" or "Hash" form), for a pipeline that reads that shape (SPEC §9.5). The members
 * and their order are those Aseprite writes.
 *
 * - A frame is named by its atlas ID: `filename` in the array form, the member name in the
 *   hash form.
 * - `frame` is the part of the atlas rectangle that lies inside the source frame: its
 *   `x, y`, and `min(w, sourceW − offsetX)` by `min(h, sourceH − offsetY)`, the content size
 *   of SPEC §9.2. The transparent column or row that makes a rectangle even is left out
 *   where it lies past the source frame, so a 33×17 frame is 33×17 here. Where a trimmed
 *   rectangle of odd content ends inside the frame, that column or row is one of the frame
 *   and stays: such a size is even.
 * - `spriteSourceSize` is where that part lies in the source frame, `sourceSize` the source
 *   frame, and `trimmed` says whether the part is less than the whole of it.
 * - `duration` is the frame's own, in milliseconds.
 * - `meta.frameTags` has one tag per animation of the atlas, under the animation's ID.
 *   `from` and `to` are positions in this file's list of frames. As in Aseprite, `repeat` is
 *   a string and is left out for a tag that plays without end, and `color` is left out when
 *   its alpha is 0 (the animation of a document without tags has none).
 * - `meta.app` and `meta.version` name this application; `scale` is the string `"1"`.
 */
export function asepriteJsonText(
    meta: AtlasMeta,
    plan: ExportPlan,
    doc: Pick<SpriteDoc, "frames">,
    form: "array" | "hash",
): string {
    const first = plan.frameIndices[0];
    const frames = plan.frameIndices.map((documentIndex) => {
        const id = frameId(plan.name, documentIndex);
        const { x, y, w, h, sourceW, sourceH, offsetX, offsetY } = meta.frames[id];
        const contentW = Math.min(w, sourceW - offsetX);
        const contentH = Math.min(h, sourceH - offsetY);
        const whole =
            offsetX === 0 && offsetY === 0 && contentW === sourceW && contentH === sourceH;
        const data = {
            frame: { x, y, w: contentW, h: contentH },
            rotated: false,
            trimmed: !whole,
            spriteSourceSize: { x: offsetX, y: offsetY, w: contentW, h: contentH },
            sourceSize: { w: sourceW, h: sourceH },
            duration: doc.frames[documentIndex].durationMs,
        };
        return { id, data };
    });
    const frameTags = plan.animations.map(({ id, playback, from, to, color }) => ({
        name: id,
        from: from - first,
        to: to - first,
        direction: playback.direction,
        ...(playback.repeat > 0 ? { repeat: String(playback.repeat) } : {}),
        ...(color !== undefined && (color & 0xff) !== 0 ? { color: hexColor(color) } : {}),
    }));
    const [app, version] = ATLAS_GENERATOR.split(" ");
    const sheet = {
        frames:
            form === "array"
                ? frames.map(({ id, data }) => ({ filename: id, ...data }))
                : Object.fromEntries(frames.map(({ id, data }) => [id, data])),
        meta: {
            app,
            version,
            image: meta.image,
            format: "RGBA8888",
            size: { w: meta.width, h: meta.height },
            scale: "1",
            frameTags,
        },
    };
    return `${JSON.stringify(sheet, null, 4)}\n`;
}
